"""Writes a Windows layout's character tables, and the typing cases that check a built DLL, as C."""

from __future__ import annotations

from collections.abc import Iterator

from .keys import COLUMNS, MODIFIERS, SHIFT, WinKey
from .tugmali import WinLayout

HEADER = "/* Generated by uzkbd/windows/build.py. Do not edit. */\n"
CAPS = "CAPS"


def to_chars_h(layout: WinLayout) -> str:
    """VK_TO_WCHARS tables, one per width as kbdus.c has them, and the table list KbdTables points to."""
    by_width: dict[int, list[WinKey]] = {}
    for key in layout.keys:
        by_width.setdefault(_width(key), []).append(key)
    # Widest first and the numpad's one-column table last, so VkKeyScan finds digits on the main keys.
    widths = sorted(by_width, key=lambda width: (width == 1, -width))
    lines = [HEADER]
    for width in widths:
        lines.append(f"static ALLOC_SECTION_LDATA VK_TO_WCHARS{width} aVkToWch{width}[] = {{")
        for key in by_width[width]:
            attributes = "CAPLOK" if key.caps else "0"
            chars = ", ".join(_wchar(ch) for ch in key.chars()[:width])
            lines.append(f"    {{ {key.vk}, {attributes}, {chars} }},")
        lines.append(f"    {{ 0, 0, {', '.join(['0'] * width)} }}")
        lines.append("};\n")
    lines.append("static ALLOC_SECTION_LDATA VK_TO_WCHAR_TABLE aVkToWcharTable[] = {")
    for width in widths:
        lines.append(f"    {{ (PVK_TO_WCHARS1)aVkToWch{width}, {width}, sizeof(aVkToWch{width}[0]) }},")
    lines.append("    { NULL, 0, 0 }")
    lines.append("};")
    return "\n".join(lines) + "\n"


def to_cases_h(layout: WinLayout) -> str:
    """Every character the layout types, as the key and modifiers that type it."""
    lines = [HEADER, "static const struct Case kCases[] = {"]
    for vk, modifiers, ch in cases(layout):
        lines.append(f'    {{ {vk}, {modifiers}, L"\\x{ord(ch):04x}" }},')
    lines.append("};")
    return "\n".join(lines) + "\n"


def cases(layout: WinLayout) -> Iterator[tuple[str, str, str]]:
    for key in layout.keys:
        for column, ch in zip(COLUMNS, key.chars(), strict=True):
            # ToUnicodeEx reports a typed NUL as no character at all, so Shift+Ctrl+2 is left out.
            if ch is not None and ch != "\x00":
                yield key.vk, str(MODIFIERS[column]), ch
        if key.caps:
            yield key.vk, CAPS, key.shift or ""
            yield key.vk, f"{CAPS} | {SHIFT}", key.base or ""


def _width(key: WinKey) -> int:
    chars = key.chars()
    return max(i for i, ch in enumerate(chars) if ch is not None) + 1


def _wchar(ch: str | None) -> str:
    if ch is None:
        return "WCH_NONE"
    if ch in "'\\":
        return f"'\\{ch}'"
    if " " <= ch <= "~":
        return f"'{ch}'"
    return f"0x{ord(ch):04x}"
