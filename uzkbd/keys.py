_CONTROL_SYMBOLS = {"[": "\x1b", "\\": "\x1c", "]": "\x1d", "6": "\x1e", "-": "\x1f"}


def control_char(base: str) -> str:
    """What Control+key types, so terminals still get ^C, ^[ and friends."""
    if "a" <= base <= "z":
        return chr(ord(base) - 0x60)
    return _CONTROL_SYMBOLS.get(base, base)
